import type { Diagnostic } from '../../shared/diagnostics';
import { createZip, type ZipEntry } from '../../shared/zip';
import { generateFiles, type GeneratedFile } from './generate';
import { fullPath, type OccConfig } from './model';

export function buildReadme(c: OccConfig, files: GeneratedFile[], diagnostics: Diagnostic[]): string {
  const warnings = diagnostics.filter((d) => d.severity === 'warning');
  const endpoints = c.endpoints.map((e) => `- \`${e.httpMethod} ${fullPath(c, e)}\` → \`${e.methodName}\``).join('\n');
  return `# ${c.controllerName} – generated OCC scaffolding

Generated by SAP Commerce Code Generator (browser-only, no SAP connection).
Selected Commerce profile: **SAP Commerce ${c.profile}** (${c.profile === '2205' ? 'Swagger v1 annotations: io.swagger.annotations' : 'OpenAPI v3 annotations: io.swagger.v3.oas.annotations'}).

## Endpoints

${endpoints}

## Files

${files.map((f) => `- \`${f.path}\` – ${f.purpose}`).join('\n')}

Paths are relative to a source root of your choosing (for example the \`src\` folder of a web extension).

## Assumptions and TODOs

- The code is **scaffolding**. Business logic, service calls, DTO mapping and persistence are intentionally not generated.
- Facade, facade implementation and validator are skeletons: declare the Spring beans yourself (bean names are referenced via \`@Resource(name = ...)\`) and implement the TODOs.
- Security: \`@Secured\` roles are taken from the configuration. OAuth clients, scopes and URL security rules must be configured in your project.
- \`{baseSiteId}\` and other path prefixes are resolved by OCC filters in your project; verify them.
- Hand-written WsDTO classes are generated for convenience. SAP Commerce projects normally generate WsDTOs from \`*-beans.xml\`; consider moving the definition there.
- Imports for the catalogue WsDTO types (ProductWsDTO, CartWsDTO, …) and \`WebserviceValidationException\` are assumptions that must be verified for your Commerce version.
- javax.* imports are generated for both profiles. Verify the namespace used by your exact patch level.

## Required project-specific wiring

1. Add the files to an extension that is part of your build and is loaded by the OCC web application.
2. Register the facade and validator beans in a Spring context loaded by the web module.
3. Make sure the controller package is covered by component scanning of the web module.
4. Add dependencies (Spring MVC, Spring Security, Swagger/OpenAPI, bean validation) as required by the extensions you already use.

## Validation limitations

The generator performs static checks on its own configuration only. It cannot prove that the generated code compiles or behaves correctly in your installation.
${warnings.length ? `\nWarnings at export time:\n\n${warnings.map((w) => `- ${w.message}`).join('\n')}\n` : ''}
## Suggested manual checks

1. Compile the extension (\`ant clean all\`) and fix any import or type issues.
2. Start the server and open the Swagger/OpenAPI UI of your OCC web application to confirm the operations appear.
3. Call each endpoint with a real OAuth token against a development system.
4. Add unit tests for the facade and validator once they are implemented.
`;
}

export function buildProjectEntries(c: OccConfig, diagnostics: Diagnostic[]): ZipEntry[] {
  const files = generateFiles(c);
  return [...files.map((f) => ({ path: f.path, content: f.content })), { path: 'README.md', content: buildReadme(c, files, diagnostics) }];
}

export function buildProjectZip(c: OccConfig, diagnostics: Diagnostic[]): Uint8Array {
  return createZip(buildProjectEntries(c, diagnostics));
}
